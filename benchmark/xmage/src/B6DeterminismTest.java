package org.mage.test.benchmark;

import mage.cards.Card;
import mage.constants.PhaseStep;
import mage.constants.Zone;
import mage.game.Game;
import mage.game.permanent.Permanent;
import mage.players.Player;
import mage.util.RandomUtil;
import org.junit.Assert;
import org.junit.Test;
import org.mage.test.serverside.base.CardTestPlayerBase;

import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

/**
 * Phase 3.1: determinism. Same seed + same scenario + same scripted
 * actions must produce an identical resulting state, 100 times.
 *
 * State is summarized canonically (sorted card names per zone, life,
 * turn) rather than via GameState.getValue(), because object UUIDs are
 * generated by UUID.randomUUID() (not RandomUtil) and would differ
 * between runs without implying gameplay nondeterminism.
 */
public class B6DeterminismTest extends CardTestPlayerBase {

    private String canonicalSummary(Game game) {
        StringBuilder sb = new StringBuilder();
        sb.append("turn=").append(game.getTurnNum());
        List<String> perms = new ArrayList<>();
        for (Permanent p : game.getBattlefield().getAllPermanents()) {
            perms.add(p.getName() + (p.isTapped() ? "/T" : "")
                    + "/dmg" + p.getDamage());
        }
        perms.sort(String::compareTo);
        sb.append("|bf=").append(perms);
        for (UUID pid : game.getState().getPlayersInRange(null, game)) {
            Player p = game.getPlayer(pid);
            sb.append("|").append(p.getName())
                    .append(":life=").append(p.getLife())
                    .append(":hand=").append(p.getHand().size());
            List<String> grave = new ArrayList<>();
            for (Card c : p.getGraveyard().getCards(game)) {
                grave.add(c.getName());
            }
            grave.sort(String::compareTo);
            sb.append(":grave=").append(grave);
        }
        return sb.toString();
    }

    private String runScriptedScenario() throws Exception {
        RandomUtil.setSeed(7);
        reset();
        addCard(Zone.BATTLEFIELD, playerA, "Mountain", 4);
        addCard(Zone.BATTLEFIELD, playerA, "Grizzly Bears", 2);
        addCard(Zone.BATTLEFIELD, playerB, "Wall of Wood", 1);
        addCard(Zone.HAND, playerA, "Lightning Bolt", 2);
        castSpell(1, PhaseStep.PRECOMBAT_MAIN, playerA, "Lightning Bolt", playerB);
        attack(3, playerA, "Grizzly Bears");
        attack(3, playerA, "Grizzly Bears");
        block(3, playerB, "Wall of Wood", "Grizzly Bears");
        castSpell(3, PhaseStep.POSTCOMBAT_MAIN, playerA, "Lightning Bolt", playerB);
        setStopAt(4, PhaseStep.UNTAP);
        execute();
        return canonicalSummary(currentGame);
    }

    @Test
    public void determinismScripted100x() throws Exception {
        String first = runScriptedScenario();
        for (int i = 1; i < 100; i++) {
            String s = runScriptedScenario();
            Assert.assertEquals("nondeterminism at iteration " + i, first, s);
        }
        System.out.println("BENCH|B6.scripted|runs=100|deterministic=true|state=" + first);
    }
}
