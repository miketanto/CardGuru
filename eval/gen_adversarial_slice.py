"""Generate a fresh adversarial slice mechanically, with no hand-picking.

research/oracle-grammar-triage.md burned a01-a05: those questions' failures were
inspected while fixing the grammar, so they can no longer score it. plan/eval.md
§B rule 2 anticipates this ("any later change is a new benchmark version"), but a
replacement slice authored by hand *after* building the grammar has its own
problem -- the author knows where the grammar is weak, and can pick questions
that flatter or punish it.

So this slice is generated by rule instead:

1. **Archetypes come from the ontology by frequency**, not from judgment. Each
   family enumerates the top-N values of a Forge vocabulary (cost atoms, trigger
   modes, static modes, replacement events) and builds one structural query per
   value.
2. **Questions are template-filled** from the archetype, so the wording is not
   chosen per question either.
3. **The witness is the Forge match that BM25 ranks highest** for the question
   text -- i.e. the card a text search would most plausibly surface, so a miss
   is a real miss rather than an obscure-card artifact.
4. **The foil is the non-matching card whose oracle text BM25 ranks closest to
   the witness's own oracle text.** Scoring foils against the *witness card's
   text* rather than against the question is what produces the a01/a05 property
   -- "textually similar, mechanically different" -- mechanically, rather than
   by someone who already knows where the grammar is weak.
5. A question is kept only if a witness and a foil both exist and the foil
   scores at least `MIN_FOIL_RATIO` of the witness's self-similarity score --
   i.e. the two really are confusable to a lexical retriever.

Everything is deterministic: same dataset in, same slice out. Freeze the output
and hash it before the first scoring run.

Usage:
    python3 eval/gen_adversarial_slice.py data/dataset.jsonl.gz eval/nl_questions_adversarial_v2.json
"""
from __future__ import annotations

import collections
import gzip
import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "eval"))

from cardguru.index import SearchIndex  # noqa: E402
from flat_baseline import BM25  # noqa: E402

TOP_N_PER_FAMILY = 6
# Rank offset: 0 takes ranks 1..N of each vocabulary, 6 takes 7..N+6, and so
# on. Because the slice is generated by rule rather than authored, a spent
# slice can be replaced by a DISJOINT one simply by advancing the offset --
# which is what makes this criterion repeatable, unlike a hand-written set.
RANK_OFFSET = int(os.environ.get('SLICE_RANK_OFFSET', '0'))
MIN_HITS, MAX_HITS = 15, 2500
MIN_FOIL_RATIO = 0.45


def load_records(path):
    opener = gzip.open if path.endswith(".gz") else open
    with opener(path, "rt", encoding="utf-8") as f:
        f.readline()
        for line in f:
            yield json.loads(line)


def strip_reminder(text: str) -> str:
    out, depth = [], 0
    for ch in text.replace("\\n", "\n"):
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth = max(0, depth - 1)
        elif depth == 0:
            out.append(ch)
    return "".join(out)


def archetypes(records):
    """Enumerate query archetypes from the ontology, top-N by frequency."""
    cost_atoms = collections.Counter()
    tmodes = collections.Counter()
    smodes = collections.Counter()
    revents = collections.Counter()
    for r in records:
        for n in r["nodes"]:
            k = n.get("kind")
            p = n.get("params") or {}
            if k == "A" and n.get("apiKind") == "AB":
                for atom in (p.get("Cost") or "").split():
                    head = atom.split("<")[0]
                    if head and not head.isdigit():
                        cost_atoms[head] += 1
            if k == "T" and n.get("mode"):
                tmodes[n["mode"]] += 1
            if k == "S" and n.get("mode"):
                smodes[n["mode"]] += 1
            if k == "R" and p.get("Event"):
                revents[p["Event"]] += 1

    out = []
    for atom, _ in cost_atoms.most_common(RANK_OFFSET + TOP_N_PER_FAMILY)[RANK_OFFSET:]:
        pretty = {"T": "tapping itself", "Sac": "sacrificing a permanent",
                  "Discard": "discarding a card",
                  "PayLife": "paying life"}.get(atom, atom)
        out.append({
            "family": "cost",
            "q": f"cards with an activated ability whose cost includes {pretty}",
            "query": {"node": {"kind": "A", "apiKind": "AB",
                               "params": {"Cost": {"regex": rf"(^|\s){atom}(<|$|\s)"}}}},
        })
    for mode, _ in tmodes.most_common(RANK_OFFSET + TOP_N_PER_FAMILY)[RANK_OFFSET:]:
        out.append({
            "family": "trigger_mode",
            "q": f"cards with a triggered ability that triggers on {mode}",
            "query": {"node": {"kind": "T", "mode": mode}},
        })
    for mode, _ in smodes.most_common(RANK_OFFSET + TOP_N_PER_FAMILY)[RANK_OFFSET:]:
        out.append({
            "family": "static_mode",
            "q": f"cards with a static ability of type {mode}",
            "query": {"node": {"kind": "S", "mode": mode}},
        })
    for ev, _ in revents.most_common(RANK_OFFSET + TOP_N_PER_FAMILY)[RANK_OFFSET:]:
        out.append({
            "family": "replacement_event",
            "q": f"cards with a replacement effect on the {ev} event",
            "query": {"node": {"kind": "R", "params": {"Event": ev}}},
        })
    return out


def main(argv):
    if len(argv) < 3:
        print(__doc__)
        return 2
    src, dst = argv[1], argv[2]
    records = list(load_records(src))
    index = SearchIndex(list(records))

    docs = {}
    for r in records:
        nm = r.get("canonicalName") or r.get("name")
        if not nm:
            continue
        docs[nm] = f"{r.get('types') or ''} {strip_reminder(r.get('oracle') or '')}"
    bm25 = BM25(docs)

    questions = []
    for i, arch in enumerate(archetypes(records)):
        hits = {(r["record"].get("canonicalName") or r["record"].get("name"))
                for r in index.search(arch["query"])}
        hits.discard(None)
        if not (MIN_HITS <= len(hits) <= MAX_HITS):
            continue
        ranked = bm25.search(arch["q"], k=400)
        witness = next((n for n, _ in ranked if n in hits), None)
        if not witness:
            continue
        # Foil: the card most textually similar to the WITNESS that does not
        # match the structural query. This is the adversarial property.
        near = bm25.search(docs[witness], k=60)
        foil = next((n for n, _ in near if n not in hits and n != witness
                     and n in docs), None)
        if not foil:
            continue
        near_scores = dict(near)
        self_score = near_scores.get(witness) or max(near_scores.values(), default=1e-9)
        if near_scores.get(foil, 0) < MIN_FOIL_RATIO * max(self_score, 1e-9):
            continue
        questions.append({
            "id": f"b{len(questions) + 1:02d}",
            "family": arch["family"],
            "q": arch["q"],
            "witness": [witness],
            "absent": [foil],
            "forge_hits": len(hits),
            "agent_query": arch["query"],
            "why_adversarial": (
                "foil is the top BM25-ranked card that does NOT match the "
                "structural query, so it is lexically confusable with the "
                "witness but mechanically different"),
        })

    payload = {
        "_comment": (
            "Adversarial slice v2, generated mechanically by "
            "eval/gen_adversarial_slice.py. Replaces a01-a05, which were burned "
            "by research/oracle-grammar-triage.md. Witness = highest BM25-ranked "
            "Forge match; foil = highest BM25-ranked non-match. No question, "
            "witness or foil was chosen by hand."),
        "generator": {
            "top_n_per_family": TOP_N_PER_FAMILY,
            "rank_offset": RANK_OFFSET,
            "min_hits": MIN_HITS, "max_hits": MAX_HITS,
            "min_foil_ratio": MIN_FOIL_RATIO,
        },
        "questions": questions,
    }
    text = json.dumps(payload, indent=1)
    with open(dst, "w", encoding="utf-8") as f:
        f.write(text + "\n")
    digest = hashlib.sha256(text.encode()).hexdigest()
    print(json.dumps({"questions": len(questions), "out": dst,
                      "sha256": digest}, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
